export function detectLang() {
  const nav = (typeof navigator !== 'undefined' && navigator.language) || 'es'
  const short = nav.slice(0, 2).toLowerCase()
  return LANGS.includes(short) ? short : 'es'
}

export const LangContext = createContext({ lang: 'es', setLang: () => {} })

export function useT() {
  const { lang } = useContext(LangContext)
  const t = (key) => (dict[lang] && dict[lang][key]) || dict.es[key] || key
  const locale = { es: 'es-MX', en: 'en-US', fr: 'fr-FR', de: 'de-DE' }[lang]
  const fmtNum = (n) => new Intl.NumberFormat(locale).format(Number(n) || 0)
  const fmtDate = (iso) => (iso ? new Date(iso).toLocaleString(locale) : '')
  return { t, lang, locale, fmtNum, fmtDate }
}
